#!/usr/bin/env node

/**
 * post-commit-review-prep.js
 *
 * Antigravity PostToolUse hook — runs after Write/Edit tool calls.
 * Detects uncommitted or recently committed changes, runs a quick
 * lint/build smoke test, and writes PENDING_REVIEW.md so the reviewer
 * model (Claude) can pick it up immediately after a model switch.
 *
 * Usage (hooks.json):
 *   { "matcher": "Edit|Write", "command": "node .agents/hooks/post-commit-review-prep.js" }
 *
 * Environment:
 *   SKIP_REVIEW_PREP=1   — disable this hook temporarily
 *   REVIEW_AUTO_LINT=0   — skip the lint step (default: run lint)
 */

const { execSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const ROOT = findProjectRoot();
const PENDING = path.join(ROOT, "PENDING_REVIEW.md");

function findProjectRoot() {
  let dir = process.cwd();
  while (dir !== path.dirname(dir)) {
    if (fs.existsSync(path.join(dir, "package.json"))) return dir;
    dir = path.dirname(dir);
  }
  return process.cwd();
}

function run(cmd, opts = {}) {
  try {
    return execSync(cmd, {
      cwd: ROOT,
      encoding: "utf-8",
      timeout: 30_000,
      stdio: ["pipe", "pipe", "pipe"],
      ...opts,
    }).trim();
  } catch (e) {
    return e.stdout ? e.stdout.trim() : `ERROR: ${e.message}`;
  }
}

function main() {
  if (process.env.SKIP_REVIEW_PREP === "1") return;

  // 1. Gather git state
  const branch = run("git branch --show-current");
  const status = run("git status -s");
  const lastCommit = run('git log -1 --format="%h %s" 2>nul') || "(no commits)";

  // Diff: staged + unstaged vs HEAD
  const diffStat = run("git diff --stat HEAD 2>nul") || "(clean tree)";
  const changedFiles = run("git diff --name-only HEAD 2>nul")
    .split("\n")
    .filter(Boolean);

  // Also include untracked files (new files not yet staged)
  const untrackedRaw = run("git ls-files --others --exclude-standard 2>nul");
  const untracked = untrackedRaw.split("\n").filter(Boolean);

  const allChanged = [...new Set([...changedFiles, ...untracked])];

  // If nothing changed, remove stale PENDING_REVIEW and exit
  if (allChanged.length === 0 && !status) {
    if (fs.existsSync(PENDING)) fs.unlinkSync(PENDING);
    return;
  }

  // 2. Optional lint check
  let lintResult = "⏭️ Skipped";
  if (process.env.REVIEW_AUTO_LINT !== "0") {
    const lintOut = run("npx next lint --quiet 2>&1");
    const hasError = /error/i.test(lintOut) && !/0 errors/i.test(lintOut);
    lintResult = hasError ? `❌ Errors detected\n\`\`\`\n${lintOut.slice(0, 1500)}\n\`\`\`` : "✅ Clean";
  }

  // 3. Categorize changed files
  const categories = {
    components: [],
    pages: [],
    api: [],
    styles: [],
    config: [],
    prisma: [],
    other: [],
  };

  for (const f of allChanged) {
    if (/src\/components/i.test(f)) categories.components.push(f);
    else if (/src\/app\/(?!api)/i.test(f)) categories.pages.push(f);
    else if (/src\/app\/api/i.test(f) || /src\/lib/i.test(f)) categories.api.push(f);
    else if (/\.(s?css|module\.)/i.test(f)) categories.styles.push(f);
    else if (/prisma/i.test(f)) categories.prisma.push(f);
    else if (/\.(json|mjs|config|env)/i.test(f)) categories.config.push(f);
    else categories.other.push(f);
  }

  // 4. Build PENDING_REVIEW.md
  const now = new Date().toISOString().replace("T", " ").slice(0, 19);
  let md = `# 🔍 Pending Review

> Auto-generated by \`post-commit-review-prep.js\` — ${now}
> **DO NOT edit manually.** This file is overwritten on every code change.

## Context

| Key | Value |
|-----|-------|
| Branch | \`${branch}\` |
| Last Commit | \`${lastCommit}\` |
| Changed Files | ${allChanged.length} |
| Lint Status | ${lintResult.split("\n")[0]} |

## Changed Files (${allChanged.length})

`;

  for (const [cat, files] of Object.entries(categories)) {
    if (files.length === 0) continue;
    md += `### ${cat.charAt(0).toUpperCase() + cat.slice(1)} (${files.length})\n`;
    for (const f of files) {
      const marker = untracked.includes(f) ? " 🆕" : "";
      md += `- \`${f}\`${marker}\n`;
    }
    md += "\n";
  }

  md += `## Diff Summary

\`\`\`
${diffStat}
\`\`\`

`;

  if (lintResult !== "✅ Clean" && lintResult !== "⏭️ Skipped") {
    md += `## Lint Issues

${lintResult}

`;
  }

  md += `## Review Instructions

When switching to **Claude** for review, use one of:

\`\`\`
/review
\`\`\`

Or prompt directly:

\`\`\`
Review the changes listed in PENDING_REVIEW.md — check for bugs, security issues, and code quality.
\`\`\`

---

*This file is gitignored and exists only as a handoff artifact between models.*
`;

  fs.writeFileSync(PENDING, md, "utf-8");
}

main();
